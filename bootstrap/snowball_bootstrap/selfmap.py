"""The brain's own map, held to its generator by the referee (`tohum/29t`; the owner's decision of 2026-11-14, E585).

`docs/map/brain.md` is the drawing of the brain's own code (`tohum/15` 4). Its header names the command that draws
it; until this check only the Founder's own test held the file to that command's output (Y6). On every push whose
tests run, `pull` reads the header (``read``: nothing runs there), and `kos` runs the command the referee composes from
it, ``python -m <module> brain .`` in `referee/`, in the tests' sandbox (no network, no secret, the locked wheels, the
tests' time limit) on the pushed tree with the map itself taken out. The output is compared byte for byte with the
committed file; only when they differ does the command run a second time, so a stale map and an unstable generator
are told apart. `decide` reads the finding: a warning in Stage 0, a reason the Founder can fix once the lock opened
Stage 1.

The header's text never reaches a shell: the module is captured by a pattern that admits only ASCII Python names
joined by dots, the command is built here, and the module must be a file under `referee/` in the pushed tree.
A pass says the file is the command's output, not that the drawing is right (E587).
"""

from __future__ import annotations

import hashlib
import re
from pathlib import Path
from typing import Any, Callable

from .container import Runner, RunResult
from .moduleless import DOCKER_ERROR, module_less_tree, output_record
from .treehash import iter_files

MAP_PATH = "docs/map/brain.md"
RUN_DIR = "referee"
HEADER_LINES = 10  # the header is read from the file's first lines only
MISSING = "self_map_missing"
UNREADABLE = "self_map_header_unreadable"
FAILED = "self_map_generator_failed"
STALE = "self_map_stale"
UNSTABLE = "self_map_unstable"
NAMES = (MISSING, UNREADABLE, FAILED, STALE, UNSTABLE)
_NAME = r"[A-Za-z_][A-Za-z0-9_]*"
MODULE = re.compile(rf"{_NAME}(?:\.{_NAME})*")
HEADER = re.compile(rf"Generated by `python -m ({MODULE.pattern}) brain \.`")
RUN_FIELDS = ("exit", "timed_out", "duration_ms", "runner_fault", "stdout_sha256", "output_sha256", "output_tail")
PROBLEMS = {  # a header the referee cannot run, each named in the finding's detail
    "missing": f"{MAP_PATH} is not a file in the pushed tree",
    "no_command": f"no line of the first {HEADER_LINES} names the command as Generated by `python -m <module> brain .`",
    "several_commands": f"the first {HEADER_LINES} lines name the command more than once",
    "module_not_in_referee": "the module is neither referee/<module path>.py nor referee/<module path>/__main__.py",
}


def command(module: str) -> str:
    """The one command the referee runs, built from a module name the pattern admits and from nothing else."""
    if not MODULE.fullmatch(module):
        raise ValueError(f"not a module name: {module!r}")
    return f"python -m {module} brain ."


def read(tar_bytes: bytes) -> dict[str, Any]:
    """`pull`'s reading of the pushed tree, which executes nothing: the module the header names, the committed
    file's sha256 and the problem that keeps the referee from running it (None when there is none)."""
    blob, paths = None, set()
    for path, content, _exec in iter_files(tar_bytes):
        name = path.as_posix()
        paths.add(name)
        if name == MAP_PATH:
            blob = content
    plan: dict[str, Any] = {"module": None, "map_sha256": None, "problem": None}
    if blob is None:
        return dict(plan, problem="missing")
    plan["map_sha256"] = hashlib.sha256(blob).hexdigest()
    head = "\n".join(line.decode("utf-8", "replace") for line in blob.split(b"\n")[:HEADER_LINES])
    found = HEADER.findall(head)
    if len(found) != 1:
        return dict(plan, problem="no_command" if not found else "several_commands")
    module = found[0]
    under = f"{RUN_DIR}/" + module.replace(".", "/")
    if f"{under}.py" not in paths and f"{under}/__main__.py" not in paths:
        return dict(plan, module=module, problem="module_not_in_referee")
    return dict(plan, module=module)


def to_run(plan: Any) -> dict[str, str] | None:
    """What `kos` runs for a plan: its module and the committed file's hash, or None when there is nothing to run."""
    if not isinstance(plan, dict) or plan.get("problem") is not None:
        return None
    return {"module": plan["module"], "map_sha256": plan["map_sha256"]}


def second_due(plan: dict[str, Any], first: dict[str, Any]) -> bool:
    """A second run follows a first that ended well with other bytes than the committed file's, and nothing else."""
    return first["exit"] == 0 and not first["timed_out"] and first["stdout_sha256"] != plan["map_sha256"]


def _record(res: RunResult) -> dict[str, Any]:
    return {"exit": res.exit_code, "timed_out": res.timed_out, "duration_ms": res.duration_ms,
            "runner_fault": res.exit_code == DOCKER_ERROR, "stdout_sha256": hashlib.sha256(res.stdout).hexdigest(),
            **output_record(res)}


def run(make_runner: Callable[[Path], Runner], tar_bytes: bytes, work: Path, plan: dict[str, Any], timeout_s: int,
        max_bytes: int) -> dict[str, Any]:
    """The generator's run on the pushed tree without the map, in `referee/`: once, twice when the first differs."""
    module_less_tree(tar_bytes, work, MAP_PATH, max_bytes)
    runner = make_runner(work)
    cmd = command(plan["module"])
    runs = [_record(runner.run(cmd, cwd=RUN_DIR, timeout_s=timeout_s))]
    if second_due(plan, runs[0]):
        runs.append(_record(runner.run(cmd, cwd=RUN_DIR, timeout_s=timeout_s)))
    return {"module": plan["module"], "map_sha256": plan["map_sha256"], "runs": runs}


def complete(plan: dict[str, Any], record: Any) -> bool:
    """Whether ``record`` is the run of ``plan``: its module and file hash, each run with exactly its fields, and a
    second run exactly when the first called for one."""
    if not (isinstance(record, dict) and set(record) == {"module", "map_sha256", "runs"}
            and record["module"] == plan["module"] and record["map_sha256"] == plan["map_sha256"]):
        return False
    runs = record["runs"]
    if not (isinstance(runs, list) and runs and all(isinstance(r, dict) and set(r) == set(RUN_FIELDS) for r in runs)):
        return False
    return len(runs) == (2 if second_due(plan, runs[0]) else 1)


def runner_fault(record: Any) -> bool:
    """Docker itself failed under one of the runs: nothing the run printed is evidence about the push."""
    return isinstance(record, dict) and any(r.get("runner_fault") for r in record.get("runs") or [])


def finding(plan: Any, record: Any) -> tuple[str, str] | None:
    """The finding of a plan and its run, with its detail (hashes, exit codes and the run's withheld tail, never the
    output); None when the committed file is the command's output, or when there is no plan."""
    if not isinstance(plan, dict):
        return None
    problem = plan.get("problem")
    if problem == "missing":
        return MISSING, PROBLEMS["missing"]
    if problem is not None:
        return UNREADABLE, f"{problem}: {PROBLEMS.get(problem, problem)}" + (
            f" (module {plan['module']})" if plan.get("module") else "")
    first = record["runs"][0]
    if first["exit"] != 0 or first["timed_out"]:
        how = "timed out" if first["timed_out"] else f"exited {first['exit']}"
        return FAILED, f"{command(plan['module'])} {how}; output tail: {first['output_tail']}"
    if first["stdout_sha256"] == plan["map_sha256"]:
        return None
    second = record["runs"][1]
    hashes = f"committed {plan['map_sha256']}, first run {first['stdout_sha256']}"
    if second["exit"] == 0 and not second["timed_out"] and second["stdout_sha256"] == first["stdout_sha256"]:
        return STALE, f"{MAP_PATH} differs from the output of {command(plan['module'])}: {hashes}"
    how = (f"second run {second['stdout_sha256']}" if second["exit"] == 0 and not second["timed_out"]
           else "second run timed out" if second["timed_out"] else f"second run exited {second['exit']}")
    return UNSTABLE, f"two runs of {command(plan['module'])} printed different bytes: {hashes}, {how}"
