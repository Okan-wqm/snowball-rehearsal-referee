class PageTest(unittest.TestCase):
    """`29t` states the rule and the names the code uses, one source each; it names no tool of the Founder's (no
    feeding), and the pages that hold the duty (`15` 4) and the `koş` job (`29b`) point to it."""

    @staticmethod
    def page(prefix):
        return next((ROOT / "spec" / "tohum").glob(f"{prefix}-*.md")).read_text(encoding="utf-8")

    def test_29t_names_each_finding_and_nothing_else(self):  # self_map_page_drops_a_name
        text = self.page("29t")
        self.assertEqual(set(re.findall(r"self_map_[a-z_]+", text)), set(selfmap.NAMES) | {"self_map_incomplete"})
        decide_py = (BOOT / "snowball_bootstrap" / "decide.py").read_text(encoding="utf-8")
        self.assertIn("kos:self_map_incomplete", decide_py)
        for fact in (f"`{selfmap.MAP_PATH}`", "`referee/`", "ilk on satırında",
                     "``Generated by `python -m <modül> brain .` ``", "`[A-Za-z_][A-Za-z0-9_]*`"):
            self.assertIn(fact, text)
        self.assertEqual(selfmap.HEADER_LINES, 10)
        lines = text.splitlines()
        self.assertLessEqual(len(lines), 80)
        self.assertEqual([n for n, line in enumerate(lines, 1) if len(line) > 120], [])

    def test_no_tool_of_the_founders_is_named(self):  # self_map_page_names_the_founders_tool
        for text in (self.page("29t"), (BOOT / "snowball_bootstrap" / "selfmap.py").read_text(encoding="utf-8")):
            for word in ("status.depmap", "off_live", "T42", "yeniden üret", "regenerat"):
                self.assertNotIn(word, text)

    def test_the_duty_and_the_job_point_to_it(self):  # self_map_15_pointer_dropped, self_map_29b_pointer_dropped
        duty = next(line for line in self.page("15").splitlines() if "bayat çizim bayat sayfadır" in line)
        self.assertIn("`29t`", duty)
        kos = next(line for line in self.page("29b").splitlines() if line.startswith("| `koş` |"))
        self.assertIn("`29t`", kos)


