class PartsTest(unittest.TestCase):
    """The join takes the map's run from exactly the part that owns the place after the last test."""

    def records(self, p, n, made=None, sandbox=None, **kw):
        made = made if made is not None else (lambda: record(one(OTHER), one(OTHER)))
        return [parts.run_part(p, k, n, sandbox or Sandbox(), 60, lambda own: [], made, **kw) for k in range(n)]

    def test_every_part_count_writes_the_single_jobs_run(self):  # self_map_every_part_runs_it, self_map_gates_green
        p = push(selfmap.to_run(plan()))
        single = parts.join(p, self.records(p, 1))
        self.assertEqual(single["self_map"], record(one(OTHER), one(OTHER)))
        self.assertTrue(single["green"])  # a stale map leaves green to the tests: `decide` judges it
        for n in (2, 4, 5, 7):
            with self.subTest(parts=n):
                records = self.records(p, n)
                self.assertEqual([k for k, r in enumerate(records) if r["self_map"] is not None], [len(TESTS) % n])
                self.assertEqual(canon_dump(parts.join(p, records)), canon_dump(single))

    def test_a_run_held_by_another_part_stops_the_join(self):  # self_map_join_takes_any_part
        p = push(selfmap.to_run(plan()))
        records = self.records(p, 4)
        records[0]["self_map"] = record(one())
        with self.assertRaises(parts.PartError):
            parts.join(p, records)
        q = push()
        records = self.records(q, 2)
        records[1]["self_map"] = record(one())
        with self.assertRaises(parts.PartError):
            parts.join(q, records)

    def test_an_owner_without_the_plans_run_stops_the_join(self):  # self_map_join_skips_the_run_check
        p = push(selfmap.to_run(plan()))
        for bad in (None, record(one(OTHER)), record(one(), module="x"), {"runs": []}):
            records = self.records(p, 3)
            records[len(TESTS) % 3]["self_map"] = bad
            with self.subTest(bad=bad), self.assertRaises(parts.PartError):
                parts.join(p, records)

    def test_the_plan_is_part_of_the_plans_hash(self):  # self_map_plan_hash_leaves_it_out
        self.assertNotEqual(push().plan_sha256(), push(selfmap.to_run(plan())).plan_sha256())
        records = self.records(push(), 1)
        with self.assertRaises(parts.PartError):
            parts.join(push(selfmap.to_run(plan())), records)

    def test_a_red_push_still_runs_it_and_a_failed_sandbox_does_not(self):  # self_map_skipped_on_red
        p = push(selfmap.to_run(plan()))
        run = parts.join(p, self.records(p, 2, sandbox=Sandbox(failing={"python -m unittest t2"})))
        self.assertFalse(run["green"])
        self.assertEqual(run["self_map"], record(one(OTHER), one(OTHER)))
        run = parts.join(p, self.records(p, 2, sandbox=Sandbox(broken=True)))
        self.assertIsNone(run["self_map"])
        self.assertEqual(run["tests"], [])


def canon_dump(run):
    return json.dumps(run, sort_keys=True)


