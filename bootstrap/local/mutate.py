def stale_anchors(root: Path = ROOT, mutants=MUTANTS) -> list[str]:
    """The mutants whose anchor is not exactly once in its file. Every shard checks them all before it runs one, so
    an anchor a change left behind stops each shard in its first second instead of surviving only in the shard that
    holds its mutant (E504)."""
    texts: dict[str, str] = {}
    stale = []
    for name, rel, old, _new, _why in mutants:
        if rel not in texts:
            path = root / rel
            texts[rel] = path.read_text(encoding="utf-8") if path.is_file() else ""
        if texts[rel].count(old) != 1:
            stale.append(f"{name} ({rel}: found {texts[rel].count(old)}x)")
    return stale


def run_mutant(index: int, mutant: tuple[str, str, str, str, str] | None) -> tuple[bool, str, float]:
    """Apply one mutant (or none: the baseline) to a fresh copy and run the unit tests there."""
    started = time.monotonic()
    with tempfile.TemporaryDirectory(prefix=f"mutant-{index}-") as tmp:
        work = Path(tmp)
        ignore = shutil.ignore_patterns("__pycache__", "node_modules", ".git")
        shutil.copytree(ROOT / "seed", work / "seed", ignore=ignore)
        # The whole spec: the stage table's test holds `stages/stage0.json` to `asama-0/14`, `09` and `10`, the vector
        # interface pages' test checks their rows in the index (E161), and the page-length test reads every page (E252).
        shutil.copytree(ROOT / "spec", work / "spec", ignore=ignore)
        # The security ledger's test checks that every CI job a row names still exists (`30e`).
        shutil.copytree(ROOT / ".github" / "workflows", work / ".github" / "workflows", ignore=ignore)
        # The documents the tests read: the gap register (E162's exit table), the generated system map (E301), the
        # scorecard (E310) and the README; the whole folder, so the next document a test reads cannot be missing.
        shutil.copytree(ROOT / "docs", work / "docs", ignore=ignore)
        shutil.copy2(ROOT / "README.md", work / "README.md")
        if mutant is not None:
            _name, rel, old, new, _why = mutant
            target = work / rel
            text = target.read_text(encoding="utf-8")
            if text.count(old) != 1:
                return False, f"ANCHOR MISSING in {rel} (found {text.count(old)}x): update the mutant", 0.0
            target.write_text(text.replace(old, new), encoding="utf-8", newline="")
        boot = work / "seed" / "bootstrap"
        env = {"PATH": "/usr/local/bin:/usr/bin:/bin", "PYTHONDONTWRITEBYTECODE": "1", "PYTHONPATH": ".:tests",
               "HOME": str(work)}
        proc = subprocess.run([sys.executable, "-m", "unittest", "discover", "-s", "tests", "-f"], cwd=boot, env=env,
                              capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=900)
    output = proc.stdout + proc.stderr
    killers = [line.split(" ")[1] for line in output.splitlines() if line.startswith(("FAIL: ", "ERROR: "))]
    return proc.returncode != 0, (killers[0] if killers else "(no test named)"), time.monotonic() - started


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--only", help="run only the mutants with these names (comma-separated)")
    parser.add_argument("--list", action="store_true", help="list the mutants and what each stands for")
    parser.add_argument("--shard", help="K/N: run every N-th mutant starting at K, so N containers can share the list")
    args = parser.parse_args()
    wanted = set(args.only.split(",")) if args.only else None
    if wanted and wanted - {m[0] for m in MUTANTS}:
        print(f"no such mutant: {', '.join(sorted(wanted - {m[0] for m in MUTANTS}))}", file=sys.stderr)
        return 2
    chosen = [(i, m) for i, m in enumerate(MUTANTS) if not wanted or m[0] in wanted]
    if args.shard:
        k, n = (int(part) for part in args.shard.split("/"))
        chosen = [(i, m) for i, m in chosen if i % n == k]
    if not chosen:
        print("no such mutant", file=sys.stderr)
        return 2
    if args.list:
        for _i, m in chosen:
            print(f"{m[0]:34} {m[4]}")
        return 0
    stale = stale_anchors()
    if stale:
        print(f"stale mutant anchors, update them first: {'; '.join(stale)}", file=sys.stderr)
        return 2
    killed, detail, _ = run_mutant(-1, None)  # without this a failing environment makes every mutant "killed"
    if killed:
        print(f"the unmutated code already fails its tests ({detail}); fix that first", file=sys.stderr)
        return 2
    survivors = []
    for i, m in chosen:
        killed, detail, seconds = run_mutant(i, m)
        print(f"{'killed  ' if killed else 'SURVIVED'} {m[0]:34} {seconds:5.1f}s  {detail}", flush=True)
        if not killed:
            survivors.append(m[0])
    print(f"\n{len(chosen) - len(survivors)}/{len(chosen)} mutants killed")
    if survivors:
        print("not measured by any test:", ", ".join(survivors))
    return 1 if survivors else 0


if __name__ == "__main__":
    sys.exit(main())
